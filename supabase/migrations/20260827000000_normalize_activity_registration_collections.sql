create or replace function public.sync_activity_dates_from_legacy_dates()
returns trigger
language plpgsql
as $$
begin
  -- Never delete an activity date: old attendance and pickup records may refer to it.
  -- Removing a date from the legacy JSON only retires it from future use.
  update public.activity_dates
  set is_active = false,
      updated_at = now()
  where activity_id = new.id
    and is_active;

  with raw_dates as (
    select public.normalization_safe_date(item.value) as activity_date, item.ordinality::integer as sort_order
    from jsonb_array_elements_text(public.normalization_jsonb_array(new.dates)) with ordinality as item(value, ordinality)
  ), valid_dates as (
    select activity_date, min(sort_order) as sort_order
    from raw_dates
    where activity_date is not null
    group by activity_date
  )
  insert into public.activity_dates (activity_id, activity_date, sort_order, is_active)
  select new.id, valid_dates.activity_date, valid_dates.sort_order, true
  from valid_dates
  on conflict (activity_id, activity_date) do update
  set sort_order = excluded.sort_order,
      is_active = true,
      updated_at = now();

  insert into public.normalization_migration_issues (source_table, source_id, source_column, source_value, details)
  select
    'activities',
    new.id::text,
    'dates',
    item.value,
    'Ignored by activity_dates because it is not a valid ISO date.'
  from jsonb_array_elements_text(public.normalization_jsonb_array(new.dates)) as item(value)
  where public.normalization_safe_date(item.value) is null
  on conflict (source_table, source_id, source_column, source_value) do nothing;

  return new;
end;
$$;

create or replace function public.sync_registration_guests_from_legacy_json()
returns trigger
language plpgsql
as $$
begin
  with legacy_guests as (
    select
      item.ordinality::integer - 1 as guest_position,
      nullif(btrim(item.value ->> 'name'), '') as display_name,
      case
        when item.value ->> 'gender' in ('male', 'female', 'other') then item.value ->> 'gender'
        else null
      end as gender,
      public.normalization_safe_timestamptz(item.value ->> 'added_at') as joined_at,
      case lower(coalesce(item.value ->> 'paid_court', '')) when 'true' then true when '1' then true else false end as paid_court,
      case lower(coalesce(item.value ->> 'paid_ac', '')) when 'true' then true when '1' then true else false end as paid_ac,
      item.value as legacy_payload
    from jsonb_array_elements(public.normalization_jsonb_array(new.guests)) with ordinality as item(value, ordinality)
  ), upserted_guests as (
    insert into public.registration_guests (
      registration_id,
      guest_position,
      display_name,
      gender,
      joined_at,
      paid_court,
      paid_ac,
      legacy_payload
    )
    select new.id, guest_position, display_name, gender, joined_at, paid_court, paid_ac, legacy_payload
    from legacy_guests
    on conflict (registration_id, guest_position) do update
    set display_name = excluded.display_name,
        gender = excluded.gender,
        joined_at = excluded.joined_at,
        paid_court = excluded.paid_court,
        paid_ac = excluded.paid_ac,
        legacy_payload = excluded.legacy_payload,
        updated_at = now()
    returning guest_position
  )
  delete from public.registration_guests as guest
  where guest.registration_id = new.id
    and not exists (
      select 1
      from legacy_guests
      where legacy_guests.guest_position = guest.guest_position
    );

  return new;
end;
$$;

create or replace function public.sync_registration_cancellation_events_from_legacy_json()
returns trigger
language plpgsql
as $$
begin
  delete from public.registration_cancellation_events
  where registration_id = new.id
    and legacy_source in ('cancelled_members', 'cancelled_guests');

  insert into public.registration_cancellation_events (
    registration_id,
    legacy_source,
    legacy_position,
    participant_type,
    display_name,
    picture_url,
    added_by,
    participant_added_at,
    legacy_payload
  )
  select
    new.id,
    entries.legacy_source,
    entries.ordinality::integer - 1,
    case when entries.legacy_source = 'cancelled_guests' or entries.value ? 'addedBy' then 'guest' else 'self' end,
    nullif(btrim(entries.value ->> 'name'), ''),
    nullif(btrim(entries.value ->> 'image'), ''),
    nullif(btrim(entries.value ->> 'addedBy'), ''),
    public.normalization_safe_timestamptz(entries.value ->> 'time'),
    entries.value
  from (
    select 'cancelled_members'::text as legacy_source, item.value, item.ordinality
    from jsonb_array_elements(public.normalization_jsonb_array(new.cancelled_members)) with ordinality as item(value, ordinality)
    union all
    select 'cancelled_guests'::text as legacy_source, item.value, item.ordinality
    from jsonb_array_elements(public.normalization_jsonb_array(new.cancelled_guests)) with ordinality as item(value, ordinality)
  ) as entries;

  return new;
end;
$$;

create or replace function public.sync_registration_activity_date_reference()
returns trigger
language plpgsql
as $$
begin
  new.activity_date_id := null;

  if new.activity_id is null or new.activity_date is null then
    return new;
  end if;

  select activity_date.id
  into new.activity_date_id
  from public.activity_dates as activity_date
  where activity_date.activity_id = new.activity_id
    and activity_date.activity_date = public.normalization_safe_date(new.activity_date)
  limit 1;

  return new;
end;
$$;

create or replace function public.sync_season_registration_date_statuses_from_legacy()
returns trigger
language plpgsql
as $$
begin
  if new.activity_id is null or new.activity_date is not null then
    return new;
  end if;

  -- A rejoin removes the date from leave_dates. Preserve the event row but
  -- reset its current state before applying the current leave list below.
  update public.season_registration_date_statuses
  set is_on_leave = false,
      updated_at = now()
  where registration_id = new.id
    and is_on_leave;

  with raw_dates as (
    select leave_date as source_date, true as is_on_leave, null::timestamptz as leave_submitted_at, null::timestamptz as rejoined_at
    from unnest(coalesce(new.leave_dates, '{}'::text[])) as leave_date

    union all

    select entry.key, false, public.normalization_safe_timestamptz(entry.value), null::timestamptz
    from jsonb_each_text(public.normalization_jsonb_object(new.leave_times)) as entry(key, value)

    union all

    select entry.key, false, null::timestamptz, public.normalization_safe_timestamptz(entry.value)
    from jsonb_each_text(public.normalization_jsonb_object(new.rejoin_times)) as entry(key, value)
  ), normalized_dates as (
    select
      public.normalization_safe_date(source_date) as activity_date,
      bool_or(is_on_leave) as is_on_leave,
      max(leave_submitted_at) as leave_submitted_at,
      max(rejoined_at) as rejoined_at
    from raw_dates
    group by public.normalization_safe_date(source_date)
  )
  insert into public.season_registration_date_statuses (
    registration_id,
    activity_date_id,
    is_on_leave,
    leave_submitted_at,
    rejoined_at
  )
  select
    new.id,
    activity_date.id,
    normalized_dates.is_on_leave,
    normalized_dates.leave_submitted_at,
    normalized_dates.rejoined_at
  from normalized_dates
  join public.activity_dates as activity_date
    on activity_date.activity_id = new.activity_id
   and activity_date.activity_date = normalized_dates.activity_date
  where normalized_dates.activity_date is not null
  on conflict (registration_id, activity_date_id) do update
  set is_on_leave = excluded.is_on_leave,
      leave_submitted_at = coalesce(excluded.leave_submitted_at, season_registration_date_statuses.leave_submitted_at),
      rejoined_at = coalesce(excluded.rejoined_at, season_registration_date_statuses.rejoined_at),
      updated_at = now();

  return new;
end;
$$;

