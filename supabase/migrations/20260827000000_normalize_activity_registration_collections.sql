-- Phase 1: normalize collection-shaped operational data without deleting the
-- legacy columns. Existing application code can continue to use the legacy
-- columns while the triggers below keep the new tables synchronized.
--
-- The legacy columns (`activities.dates`, `registrations.guests`,
-- `leave_dates`, `leave_times`, `rejoin_times`, `cancelled_members`, and
-- `cancelled_guests`) deliberately remain in place. Do not remove them until
-- all read paths have moved to the normalized tables and a retention period
-- has elapsed.

create table if not exists public.normalization_migration_issues (
  id bigint generated by default as identity primary key,
  source_table text not null,
  source_id text not null,
  source_column text not null,
  source_value text not null,
  details text not null,
  detected_at timestamptz not null default now()
);

create unique index if not exists normalization_migration_issues_source_unique
  on public.normalization_migration_issues (source_table, source_id, source_column, source_value);

alter table public.normalization_migration_issues enable row level security;

create or replace function public.normalization_safe_date(value text)
returns date
language plpgsql
immutable
as $$
begin
  if value is null or value !~ '^\d{4}-\d{2}-\d{2}$' then
    return null;
  end if;

  return value::date;
exception
  when others then
    return null;
end;
$$;

create or replace function public.normalization_safe_timestamptz(value text)
returns timestamptz
language plpgsql
stable
as $$
begin
  if nullif(btrim(value), '') is null then
    return null;
  end if;

  return value::timestamptz;
exception
  when others then
    return null;
end;
$$;

create or replace function public.normalization_jsonb_array(value jsonb)
returns jsonb
language sql
immutable
as $$
  select case when jsonb_typeof(value) = 'array' then value else '[]'::jsonb end;
$$;

create or replace function public.normalization_jsonb_object(value jsonb)
returns jsonb
language sql
immutable
as $$
  select case when jsonb_typeof(value) = 'object' then value else '{}'::jsonb end;
$$;

